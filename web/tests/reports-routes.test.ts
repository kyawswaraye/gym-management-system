import { describe, expect, it } from "vitest";

import {
  allowsReportExport,
  allowsReportRoute,
} from "@/lib/api/reports-routes";

describe("report route allowlist", () => {
  it("forwards only the daily date and the monthly year and month", () => {
    expect(
      allowsReportRoute("/api/v1/reports/daily/", "?date=2026-10-01", "GET"),
    ).toBe(true);
    expect(
      allowsReportRoute(
        "/api/v1/reports/monthly/",
        "?year=2026&month=10",
        "GET",
      ),
    ).toBe(true);
    expect(
      allowsReportRoute("/api/v1/reports/daily/", "?date=2026-02-31", "GET"),
    ).toBe(false);
    expect(
      allowsReportRoute("/api/v1/reports/daily/", "?date=1899-12-31", "GET"),
    ).toBe(false);
    expect(allowsReportRoute("/api/v1/reports/daily/", "", "GET")).toBe(false);
    expect(
      allowsReportRoute(
        "/api/v1/reports/daily/",
        "?date=2026-10-01&gym_id=other",
        "GET",
      ),
    ).toBe(false);
    expect(
      allowsReportRoute(
        "/api/v1/reports/daily/",
        "?date=2026-10-01&status=POSTED&formula=cash",
        "GET",
      ),
    ).toBe(false);
    expect(
      allowsReportRoute("/api/v1/reports/monthly/", "?year=2026", "GET"),
    ).toBe(false);
    expect(
      allowsReportRoute(
        "/api/v1/reports/monthly/",
        "?year=2026&month=13",
        "GET",
      ),
    ).toBe(false);
    expect(
      allowsReportRoute(
        "/api/v1/reports/monthly/",
        "?year=2100&month=1",
        "GET",
      ),
    ).toBe(false);
    expect(
      allowsReportRoute("/api/v1/reports/daily/", "?date=2026-10-01", "POST"),
    ).toBe(false);
    expect(allowsReportRoute("/api/v1/dashboard/", "?range=today", "GET")).toBe(
      null,
    );
    expect(
      allowsReportRoute(
        "/api/v1/reports/cash-book/",
        "?date_from=2026-10-01&date_to=2026-10-03",
        "GET",
      ),
    ).toBe(true);
    expect(
      allowsReportRoute(
        "/api/v1/reports/profit-loss/",
        "?date_from=2024-01-01&date_to=2024-12-31",
        "GET",
      ),
    ).toBe(true);
    expect(
      allowsReportRoute(
        "/api/v1/reports/profit-loss/",
        "?date_from=2024-02-28&date_to=2024-03-01",
        "GET",
      ),
    ).toBe(true);
    expect(
      allowsReportRoute(
        "/api/v1/reports/cash-book/",
        "?date_from=2024-01-01&date_to=2025-01-01",
        "GET",
      ),
    ).toBe(false);
    expect(
      allowsReportRoute(
        "/api/v1/reports/cash-book/",
        "?date_from=2026-10-02&date_to=2026-10-01",
        "GET",
      ),
    ).toBe(false);
    expect(
      allowsReportRoute(
        "/api/v1/reports/profit-loss/",
        "?date_from=2026-10-01&date_to=2026-10-01&gym_id=other",
        "GET",
      ),
    ).toBe(false);
    expect(
      allowsReportRoute(
        "/api/v1/reports/cash-book/",
        "?date_from=2026-10-01&date_from=2026-10-02&date_to=2026-10-02",
        "GET",
      ),
    ).toBe(false);
    expect(
      allowsReportRoute(
        "/api/v1/reports/profit-loss/",
        "?date_from=&date_to=2026-10-01",
        "GET",
      ),
    ).toBe(false);
    expect(
      allowsReportRoute(
        "/api/v1/reports/cash-book/",
        "?date_from=1899-12-31&date_to=1899-12-31",
        "GET",
      ),
    ).toBe(false);
    expect(
      allowsReportRoute(
        "/api/v1/reports/cash-book/",
        "?date_from=2026-10-01&date_to=2026-10-01",
        "POST",
      ),
    ).toBe(false);
    for (const path of [
      "/api/v1/reports/membership-expiry/",
      "/api/v1/reports/check-ins/",
      "/api/v1/reports/pt-sessions/",
      "/api/v1/reports/classes/",
    ]) {
      expect(
        allowsReportRoute(
          path,
          "?date_from=2026-10-01&date_to=2026-10-03",
          "GET",
        ),
      ).toBe(true);
      expect(
        allowsReportRoute(
          path,
          "?date_from=2024-01-01&date_to=2024-12-31",
          "GET",
        ),
      ).toBe(true);
      expect(
        allowsReportRoute(
          path,
          "?date_from=2024-01-01&date_to=2025-01-01",
          "GET",
        ),
      ).toBe(false);
      expect(
        allowsReportRoute(
          path,
          "?date_from=2026-10-01&date_to=2026-10-01&gym_id=other",
          "GET",
        ),
      ).toBe(false);
      expect(
        allowsReportRoute(
          path,
          "?date_from=2026-10-01&date_from=2026-10-02&date_to=2026-10-02",
          "GET",
        ),
      ).toBe(false);
      expect(
        allowsReportRoute(path, "?date_from=&date_to=2026-10-01", "GET"),
      ).toBe(false);
      expect(
        allowsReportRoute(
          path,
          "?date_from=2026-10-01&date_to=2026-10-01",
          "POST",
        ),
      ).toBe(false);
    }
    expect(
      allowsReportRoute(
        "/api/v1/reports/stock-movements/",
        "?date_from=2026-10-01&date_to=2026-10-03",
        "GET",
      ),
    ).toBe(true);
    expect(
      allowsReportRoute(
        "/api/v1/reports/stock-movements/",
        "?date_from=2026-10-01&date_to=2026-10-03&limit=25",
        "GET",
      ),
    ).toBe(false);
    expect(
      allowsReportRoute(
        "/api/v1/reports/product-sales/",
        "?date_from=2026-10-01&date_to=2026-10-03",
        "GET",
      ),
    ).toBe(true);
    expect(
      allowsReportRoute(
        "/api/v1/reports/product-sales/",
        "?date_from=2026-10-01&date_to=2026-10-03&limit=25&after=cursor",
        "GET",
      ),
    ).toBe(true);
    expect(
      allowsReportRoute(
        "/api/v1/reports/product-sales/",
        "?date_from=2026-10-01&date_to=2026-10-03&limit=0",
        "GET",
      ),
    ).toBe(false);
    expect(
      allowsReportRoute(
        "/api/v1/reports/product-sales/",
        "?date_from=2026-10-01&date_to=2026-10-03&limit=101",
        "GET",
      ),
    ).toBe(false);
    expect(
      allowsReportRoute(
        "/api/v1/reports/product-sales/",
        "?date_from=2026-10-01&date_to=2026-10-03&gym_id=other",
        "GET",
      ),
    ).toBe(false);
    expect(allowsReportRoute("/api/v1/reports/inventory/", "", "GET")).toBe(
      true,
    );
    expect(
      allowsReportRoute(
        "/api/v1/reports/inventory/",
        "?limit=25&after=cursor",
        "GET",
      ),
    ).toBe(true);
    expect(
      allowsReportRoute(
        "/api/v1/reports/inventory/",
        "?date_from=2026-10-01&date_to=2026-10-03",
        "GET",
      ),
    ).toBe(false);
    expect(
      allowsReportRoute("/api/v1/reports/inventory/", "?limit=25", "POST"),
    ).toBe(false);
  });

  it("forwards the trainer dashboard preset or custom range and the session report", () => {
    expect(
      allowsReportRoute("/api/v1/trainer/dashboard/", "?range=today", "GET"),
    ).toBe(true);
    expect(
      allowsReportRoute(
        "/api/v1/trainer/dashboard/",
        "?range=this_year",
        "GET",
      ),
    ).toBe(true);
    expect(
      allowsReportRoute(
        "/api/v1/trainer/dashboard/",
        "?date_from=2024-01-01&date_to=2024-12-31",
        "GET",
      ),
    ).toBe(true);
    expect(
      allowsReportRoute(
        "/api/v1/trainer/reports/sessions/",
        "?date_from=2026-10-01&date_to=2026-10-03",
        "GET",
      ),
    ).toBe(true);
    expect(allowsReportRoute("/api/v1/trainer/dashboard/", "", "GET")).toBe(
      false,
    );
    expect(
      allowsReportRoute(
        "/api/v1/trainer/dashboard/",
        "?range=yesterday",
        "GET",
      ),
    ).toBe(false);
    expect(
      allowsReportRoute(
        "/api/v1/trainer/dashboard/",
        "?range=today&date_from=2026-10-01&date_to=2026-10-01",
        "GET",
      ),
    ).toBe(false);
    expect(
      allowsReportRoute(
        "/api/v1/trainer/dashboard/",
        "?range=today&range=this_week",
        "GET",
      ),
    ).toBe(false);
    expect(
      allowsReportRoute(
        "/api/v1/trainer/dashboard/",
        "?date_from=2026-10-02&date_to=2026-10-01",
        "GET",
      ),
    ).toBe(false);
    expect(
      allowsReportRoute(
        "/api/v1/trainer/dashboard/",
        "?date_from=2024-01-01&date_to=2025-01-01",
        "GET",
      ),
    ).toBe(false);
    expect(
      allowsReportRoute(
        "/api/v1/trainer/dashboard/",
        "?date_from=2026-10-01&date_to=2026-10-01&gym_id=other",
        "GET",
      ),
    ).toBe(false);
    expect(
      allowsReportRoute("/api/v1/trainer/dashboard/", "?range=today", "POST"),
    ).toBe(false);
    expect(
      allowsReportRoute(
        "/api/v1/trainer/reports/sessions/",
        "?date_from=2023-02-29&date_to=2023-02-29",
        "GET",
      ),
    ).toBe(false);
    expect(
      allowsReportRoute(
        "/api/v1/trainer/reports/sessions/",
        "?date_from=2026-10-01&date_to=2026-10-01",
        "POST",
      ),
    ).toBe(false);
    expect(
      allowsReportRoute("/api/v1/trainer/dashboard/extra/", "", "GET"),
    ).toBe(null);
  });

  it("forwards report exports without page cursors or trainer routes", () => {
    expect(
      allowsReportExport(
        "/api/v1/reports/daily/export/",
        "?date=2026-10-01",
        "GET",
      ),
    ).toBe(true);
    expect(
      allowsReportExport(
        "/api/v1/reports/product-sales/export/",
        "?date_from=2026-10-01&date_to=2026-10-04",
        "GET",
      ),
    ).toBe(true);
    expect(
      allowsReportExport(
        "/api/v1/reports/product-sales/export/",
        "?date_from=2026-10-01&date_to=2026-10-04&after=cursor",
        "GET",
      ),
    ).toBe(false);
    expect(
      allowsReportExport(
        "/api/v1/reports/product-sales/export/",
        "?date_from=2026-10-01&date_to=2026-10-04&limit=25",
        "GET",
      ),
    ).toBe(false);
    expect(
      allowsReportExport("/api/v1/reports/inventory/export/", "", "GET"),
    ).toBe(true);
    expect(
      allowsReportExport(
        "/api/v1/reports/inventory/export/",
        "?limit=25",
        "GET",
      ),
    ).toBe(false);
    expect(
      allowsReportExport(
        "/api/v1/reports/check-ins/export/",
        "?date_from=2024-01-01&date_to=2024-12-31",
        "GET",
      ),
    ).toBe(true);
    expect(
      allowsReportExport(
        "/api/v1/reports/check-ins/export/",
        "?date_from=2024-01-01&date_to=2025-01-01",
        "GET",
      ),
    ).toBe(false);
    expect(
      allowsReportRoute(
        "/api/v1/trainer/dashboard/export/",
        "?range=today",
        "GET",
      ),
    ).toBe(null);
    expect(
      allowsReportRoute(
        "/api/v1/trainer/reports/sessions/export/",
        "?date_from=2026-10-01&date_to=2026-10-01",
        "GET",
      ),
    ).toBe(null);
    expect(allowsReportRoute("/api/v1/reports/exports/", "", "GET")).toBe(null);
  });
});
