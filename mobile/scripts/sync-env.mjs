import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const source = readFileSync(resolve(root, ".env"), "utf8");
const allowed = new Set(["API_BASE_URL", "APP_ENV"]);
const values = {
  API_BASE_URL: "http://10.0.2.2:8000",
  APP_ENV: "debug",
};

for (const line of source.split("\n")) {
  const trimmed = line.trim();
  if (!trimmed || trimmed.startsWith("#")) {
    continue;
  }
  const separator = trimmed.indexOf("=");
  if (separator < 1) {
    throw new Error("Each .env line must be KEY=VALUE.");
  }
  const key = trimmed.slice(0, separator).trim();
  const value = trimmed.slice(separator + 1).trim();
  if (!allowed.has(key)) {
    throw new Error(`Unsupported environment key: ${key}`);
  }
  values[key] = value;
}

const output = `/** Generated by npm run env:sync. Do not put secrets in this file. */
export const localEnv = {
  API_BASE_URL: ${JSON.stringify(values.API_BASE_URL)},
  APP_ENV: ${JSON.stringify(values.APP_ENV)},
} as const;
`;
writeFileSync(resolve(root, "src/config/env.local.ts"), output);
process.stdout.write("Wrote src/config/env.local.ts\n");
